const TEXTS: Record<Lang, TontineText> = { fr, wo, en, ar };

/** The tontine texts in the visitor's language, and a month label ("octobre 2026") in that language */
export function useTontineText() {
  const { lang } = useI18n();
  const locale = lang === "en" ? "en-GB" : lang === "ar" ? "ar-u-nu-latn" : "fr-FR";
  const monthName = (key: string) =>
    new Date(Number(key.slice(0, 4)), Number(key.slice(5)) - 1, 15).toLocaleDateString(locale, { month: "long", year: "numeric" });
  const dayName = (iso: string) => new Date(`${iso}T12:00:00`).toLocaleDateString(locale, { day: "numeric", month: "short" });
  return { tt: TEXTS[lang], lang, monthName, dayName };
}
